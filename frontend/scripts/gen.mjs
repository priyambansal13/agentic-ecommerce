#!/usr/bin/env node
/**
 * Frontend generators (zero dependencies). Run from the frontend repo root:
 *
 *   pnpm gen zone <name> --base /<path> [--port N] [--owner team-x] [--title Label]
 *        → apps/<name>/ — independently deployable Next.js 16 micro-frontend (Multi-Zones) with basePath,
 *          shared header, zone BFF (agent proxy), Dockerfile, zone card; registered in zones.json
 *          (the shell's rewrites pick it up on next start/build)
 *   pnpm gen sync
 *        → regenerate every zone's Dockerfile, README.md and .env.example from zones.json
 */
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const ZONES_FILE = join(ROOT, 'zones.json');
const argv = process.argv.slice(2);
const opt = (n) => {
  const i = argv.indexOf(n);
  return i >= 0 ? argv[i + 1] : undefined;
};
const positional = argv.filter((a, i) => !a.startsWith('--') && !['--base', '--port', '--owner', '--title'].includes(argv[i - 1]));
const [command, nameArg] = positional;
const ok = (m) => console.log(`  ✔ ${m}`);
const die = (m) => {
  console.error(`  ✖ ${m}`);
  process.exit(1);
};
const kebab = (s) => (s ?? '').trim().toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '');
const envKey = (name) => `ZONE_${name.toUpperCase().replace(/-/g, '_')}_URL`;
const readZones = () => JSON.parse(readFileSync(ZONES_FILE, 'utf8'));
function write(file, content, { overwrite = false } = {}) {
  if (existsSync(file) && !overwrite) return;
  mkdirSync(dirname(file), { recursive: true });
  writeFileSync(file, typeof content === 'string' ? content : `${JSON.stringify(content, null, 2)}\n`);
}

// ───────────────────────────────────────────── generated per-zone artefacts
function dockerfile(z, all) {
  const shellArgs =
    z.name === 'shell'
      ? all
          .filter((x) => x.basePath)
          .map((x) => `ARG ${envKey(x.name)}=http://zone-${x.name}:${x.port}\nENV ${envKey(x.name)}=$${envKey(x.name)}`)
          .join('\n')
      : '';
  return `# syntax=docker/dockerfile:1.7
# ${z.name} micro-frontend image — build from the frontend repo root:
#   docker build -f apps/${z.name}/Dockerfile -t ac/zone-${z.name} .     (or: ac docker build ${z.name})
# @ac/* libraries come from the registry (AC_REGISTRY). GENERATED by \`pnpm gen sync\`.
FROM node:24-slim AS base
ENV PNPM_HOME=/pnpm PATH=/pnpm:$PATH CI=true NEXT_TELEMETRY_DISABLED=1
RUN npm install -g pnpm@12.14.0 >/dev/null
WORKDIR /repo

FROM base AS build
ARG AC_REGISTRY=http://host.docker.internal:54873/
${shellArgs ? `# rewrites are resolved at build time → zone URLs are build args (Kubernetes Service names zone-<name> in ac-apps)\n${shellArgs}\n` : ''}COPY . .
# CI passes the registry auth as a BuildKit secret (never stored in a layer): --secret id=npmrc,src=.npmrc
RUN --mount=type=secret,id=npmrc,required=false \\
    if [ -f /run/secrets/npmrc ]; then cp /run/secrets/npmrc .npmrc; else printf '@ac:registry=%s\\n' "$AC_REGISTRY" > .npmrc; fi \\
    && pnpm install --frozen-lockfile --filter "@ac/zone-${z.name}..."
RUN pnpm exec turbo run build --filter "@ac/zone-${z.name}..."

FROM node:24-slim AS runtime
ENV NODE_ENV=production PORT=${z.port} HOSTNAME=0.0.0.0 NEXT_TELEMETRY_DISABLED=1
WORKDIR /app
COPY --from=build --chown=node:node /repo/apps/${z.name}/.next/standalone ./
COPY --from=build --chown=node:node /repo/apps/${z.name}/.next/static ./apps/${z.name}/.next/static
COPY --from=build --chown=node:node /repo/apps/${z.name}/public ./apps/${z.name}/public
USER node
EXPOSE ${z.port}
CMD ["node", "apps/${z.name}/server.js"]
`;
}

const envExample = (z, all) => {
  const lines = [`# ${z.name} zone — \`ac configure\` generates .env.local. Server-side only (never NEXT_PUBLIC_ secrets).`, 'KONG_URL=http://localhost:58000', 'NEXT_PUBLIC_APP_URL=http://localhost:3300', 'AUTH_SECRET=', 'AUTH_ISSUER_BASE=http://localhost:58180', 'AUTH_CUSTOMERS_CLIENT_ID=web', 'AUTH_CUSTOMERS_CLIENT_SECRET=', 'AUTH_STAFF_CLIENT_ID=web-admin', 'AUTH_STAFF_CLIENT_SECRET='];
  if (z.name === 'shell') for (const x of all.filter((y) => y.basePath)) lines.push(`${envKey(x.name)}=http://localhost:${x.port}`);
  return `${lines.join('\n')}\n`;
};

const card = (z) => `# ${z.name} zone

${z.description ?? (z.name === 'shell' ? "Entry point of the site: owns \`/\` and the global layout, and rewrites every zone's basePath to that zone (Next.js Multi-Zones)." : `Micro-frontend for \`${z.basePath}\`.`)}

| | |
|---|---|
| Owner | ${z.owner} |
| Route prefix | ${z.basePath || '`/` (shell)'} |
| Dev port | ${z.port} — but browse via the shell: http://localhost:3300${z.basePath} |
| Agents hosted | ${(z.agents ?? []).map((a) => `\`${a}\``).join(', ') || '—'} (BFF: \`${z.basePath}/api/agents/<id>/run\`) |
| Package / image | \`@ac/zone-${z.name}\` / \`ac/zone-${z.name}\` — \`apps/${z.name}/Dockerfile\` |

Rules: link to other zones with \`<ZoneLink>\` (hard navigation); fetch backend data server-side via \`kongFetch\` from \`@ac/bff\`;
no imports from other zones — only from \`packages/*\` and versioned \`@ac/contracts\` / \`@ac/money\`.

<!-- GENERATED by \`pnpm gen sync\` from zones.json -->
`;

function syncZone(z, all) {
  const base = join(ROOT, 'apps', z.name);
  write(join(base, 'Dockerfile'), dockerfile(z, all), { overwrite: true });
  write(join(base, '.env.example'), envExample(z, all), { overwrite: true });
  write(join(base, 'README.md'), card(z), { overwrite: true });
}

// ───────────────────────────────────────────── gen zone
function scaffold(z) {
  const base = join(ROOT, 'apps', z.name);
  const isShell = z.name === 'shell';
  write(join(base, 'package.json'), {
    name: `@ac/zone-${z.name}`,
    version: '0.1.0',
    private: true,
    type: 'module',
    ac: { kind: 'zone', port: z.port, basePath: z.basePath, owner: z.owner },
    scripts: {
      dev: `next dev -p ${z.port}`,
      build: 'next build',
      start: `next start -p ${z.port}`,
      typecheck: 'tsc --noEmit',
      lint: 'oxlint src',
      test: 'vitest run --passWithNoTests',
    },
    dependencies: {
      '@ac/agent-widget': 'workspace:^',
      '@ac/bff': 'workspace:^',
      '@ac/contracts': '^0.3.0',
      '@ac/money': '^0.1.0',
      '@ac/ui': 'workspace:^',
      next: '16.4.2',
      react: '19.3.0',
      'react-dom': '19.3.0',
    },
    devDependencies: {
      '@tailwindcss/postcss': '^4.3.3',
      '@types/node': '^24.0.0',
      '@types/react': '^19.3.0',
      '@types/react-dom': '^19.3.0',
      oxlint: '^1.89.0',
      tailwindcss: '^4.3.3',
      typescript: '^6.0.2',
      vitest: '^4.1.2',
    },
  });
  write(join(base, 'tsconfig.json'), {
    compilerOptions: {
      target: 'ES2023',
      lib: ['dom', 'dom.iterable', 'esnext'],
      skipLibCheck: true,
      strict: true,
      noEmit: true,
      esModuleInterop: true,
      module: 'esnext',
      moduleResolution: 'bundler',
      resolveJsonModule: true,
      isolatedModules: true,
      jsx: 'react-jsx',
      incremental: true,
      plugins: [{ name: 'next' }],
      paths: { '@/*': ['./src/*'] },
    },
    include: ['next-env.d.ts', '**/*.ts', '**/*.tsx', '.next/types/**/*.ts'],
    exclude: ['node_modules'],
  });
  write(join(base, 'postcss.config.mjs'), `export default { plugins: { '@tailwindcss/postcss': {} } };\n`);
  write(join(base, 'public/.gitkeep'), '');
  write(
    join(base, 'next.config.ts'),
    isShell
      ? `import type { NextConfig } from 'next';
import { readFileSync } from 'node:fs';
import { join } from 'node:path';

/**
 * Shell zone: owns '/', and rewrites each zone's basePath to that zone (Next.js Multi-Zones).
 * Zone URLs: ZONE_<NAME>_URL (Kubernetes Service names zone-<name> in Docker builds) else http://localhost:<port>.
 * Rewrites are resolved at BUILD time for standalone output — set the env/build args before \`next build\`.
 */
interface Zone {
  name: string;
  port: number;
  basePath: string;
}
const { zones } = JSON.parse(readFileSync(join(process.cwd(), '../../zones.json'), 'utf8')) as { zones: Zone[] };
const zoneUrl = (z: Zone) => process.env[\`ZONE_\${z.name.toUpperCase().replace(/-/g, '_')}_URL\`] ?? \`http://localhost:\${z.port}\`;

const nextConfig: NextConfig = {
  output: 'standalone',
  outputFileTracingRoot: join(process.cwd(), '../..'),
  poweredByHeader: false,
  async rewrites() {
    return zones
      .filter((z) => z.basePath)
      .flatMap((z) => [
        { source: z.basePath, destination: \`\${zoneUrl(z)}\${z.basePath}\` },
        { source: \`\${z.basePath}/:path*\`, destination: \`\${zoneUrl(z)}\${z.basePath}/:path*\` },
      ]);
  },
};

export default nextConfig;
`
      : `import type { NextConfig } from 'next';
import { join } from 'node:path';

/** ${z.name} zone — served under ${z.basePath} (the shell rewrites ${z.basePath}/* here). */
const nextConfig: NextConfig = {
  basePath: '${z.basePath}',
  output: 'standalone',
  outputFileTracingRoot: join(process.cwd(), '../..'),
  poweredByHeader: false,
};

export default nextConfig;
`,
  );
  write(
    join(base, 'src/app/globals.css'),
    `@import "tailwindcss";
@import "@ac/ui/tokens.css";
/* Tailwind must also scan the shared component packages */
@source "../../node_modules/@ac/ui/dist";
@source "../../node_modules/@ac/agent-widget/dist";
`,
  );
  write(
    join(base, 'src/app/layout.tsx'),
    `import { getSession } from '@ac/bff';
import { SiteHeader } from '@ac/ui';
import type { Metadata } from 'next';
import './globals.css';

export const metadata: Metadata = { title: '${z.title} · Agentic Commerce' };

export default async function RootLayout({ children }: { children: React.ReactNode }) {
  const session = await getSession();
  return (
    <html lang="en">
      <body className="min-h-screen antialiased">
        <SiteHeader${isShell ? '' : ` current="${z.basePath}"`} user={session && { name: session.name, roles: session.roles }} returnTo="${z.basePath || '/'}" />
        {children}
      </body>
    </html>
  );
}
`,
  );
  write(
    join(base, 'src/app/page.tsx'),
    `import { Page } from '@ac/ui';

export default function ${z.name.replace(/(^|-)([a-z])/g, (_, __, c) => c.toUpperCase())}Home() {
  return <Page title="${z.title}" intro="${z.description ?? 'TODO: what this zone does.'}" />;
}
`,
  );
  write(
    join(base, 'src/app/api/health/route.ts'),
    `/** Liveness for container/ECS health checks: GET ${z.basePath}/api/health */
export const dynamic = 'force-dynamic';
export function GET() {
  return Response.json({ status: 'ok', zone: '${z.name}' });
}
`,
  );
  if (!isShell)
    write(
      join(base, 'src/app/api/agents/[agentId]/run/route.ts'),
      `import { agentRoute } from '@ac/bff';

/** Zone BFF for AG-UI: ${z.basePath}/api/agents/<id>/run → Kong → agents service. Only this zone's agents. */
export const dynamic = 'force-dynamic';
export const POST = agentRoute({ allow: ${JSON.stringify(z.agents ?? ['ping'])} });
`,
    );
}

function genZone() {
  const name = kebab(nameArg);
  const basePath = opt('--base');
  if (!name || !basePath?.startsWith('/')) die('usage: pnpm gen zone <name> --base /<path> [--port N] [--owner team-x] [--title Label]');
  const cfg = readZones();
  if (cfg.zones.some((z) => z.name === name || z.basePath === basePath)) die(`zone ${name} or basePath ${basePath} already exists`);
  const used = new Set(cfg.zones.map((z) => z.port));
  let port = Number(opt('--port') ?? 3301);
  while (!opt('--port') && used.has(port)) port++;
  const z = { name, port, basePath, owner: opt('--owner') ?? 'TODO', title: opt('--title') ?? name, agents: ['ping'] };
  cfg.zones.push(z);
  writeFileSync(ZONES_FILE, `${JSON.stringify(cfg, null, 2)}\n`);
  scaffold(z);
  syncZone(z, cfg.zones);
  ok(`apps/${name} (port ${port}, ${basePath}) registered in zones.json`);
  console.log(`  · next: pnpm install → restart the shell (rewrites) → http://localhost:3300${basePath}; add a nav item in @ac/ui if it needs one`);
}

switch (command) {
  case 'zone':
    genZone();
    break;
  case 'scaffold-all': // initial repo creation: scaffold every zone listed in zones.json (keeps existing files)
    for (const z of readZones().zones) scaffold(z);
    ok('scaffolded zones from zones.json');
  // falls through
  case 'sync': {
    const { zones } = readZones();
    for (const z of zones) syncZone(z, zones);
    ok(`synced Dockerfile, README.md, .env.example for ${zones.length} zones`);
    break;
  }
  default:
    die('usage: pnpm gen <zone|sync> …');
}
